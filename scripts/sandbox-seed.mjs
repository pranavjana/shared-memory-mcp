export function assertSandbox(env) {
  if (
    env.APP_ENV !== "sandbox" ||
    env.RAILWAY_ENVIRONMENT_NAME !== "sandbox" ||
    env.RAILWAY_ENVIRONMENT_ID !== "2ef88b92-bf75-4b31-ac2b-0c5b61627732" ||
    env.RAILWAY_PROJECT_ID !== "e13f89d3-e41a-4e89-96b8-dbdc0b1f87cd" ||
    env.FALKORDB_GRAPH !== "sandbox_profiles" ||
    env.FALKORDB_MEMORY_GRAPH !== "sandbox_memory" ||
    env.SANDBOX_CLERK_APP_ID !== "app_3Kkji888RWnY1TIAjHITY6ZaF92" ||
    env.SANDBOX_CLERK_INSTANCE_ID !== "ins_3KkjiF7zViWlDNsHyTasXpqvaCC" ||
    !env.CLERK_SECRET_KEY?.startsWith("sk_test_") ||
    !env.CLERK_PUBLISHABLE_KEY?.startsWith("pk_test_") ||
    Buffer.from(env.CLERK_PUBLISHABLE_KEY.slice(8), "base64").toString() !==
      "up-burro-4657.clerk.accounts.dev$"
  ) {
    throw new Error(
      "Seed refused: the dedicated Railway sandbox and Clerk instance are required.",
    );
  }
}

export class FixtureStateError extends Error {}

export function parseSeedArgs(args) {
  const options = {
    apply: false,
    ownerEmail: "pranavjana2003@gmail.com",
    demoUpdate: undefined,
    restoreDemoMembership: false,
  };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === "--apply") options.apply = true;
    else if (arg === "--restore-demo-membership")
      options.restoreDemoMembership = true;
    else if (arg === "--owner-email" || arg === "--demo-update") {
      const value = args[++i];
      if (!value || value.startsWith("--"))
        throw new FixtureStateError(`${arg} needs a value.`);
      if (arg === "--owner-email")
        options.ownerEmail = value.trim().toLowerCase();
      else options.demoUpdate = value;
    } else
      throw new FixtureStateError(
        "Unsupported seed option; no reset/delete operation exists.",
      );
  }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(options.ownerEmail))
    throw new FixtureStateError("A valid sandbox owner email is required.");
  if (
    options.demoUpdate &&
    (options.demoUpdate.length < 8 || options.demoUpdate.length > 120)
  )
    throw new FixtureStateError(
      "Demo update keys must have 8-120 characters; reuse the key for retries.",
    );
  return options;
}

export async function seedWorkspace(memory, owner, demo, options = {}) {
  const space =
    (await memory.spaces(owner)).find(
      (s) => s.owner === owner.userId && s.name === "Sandbox collaboration",
    ) ?? (await memory.createSpace(owner, "Sandbox collaboration"));
  const memberships = await memory.query(
    "MATCH (:Person {id:$user})-[m:MEMBER_OF]->(:Space {id:$space}) RETURN m.active AS active,m.role AS role",
    { user: demo.userId, space: space.id },
    true,
  );
  const membership = memberships[0];
  if (
    !membership ||
    ((!membership.active || membership.role !== "contributor") &&
      options.restoreDemoMembership)
  ) {
    const invite = await memory.invite(
      owner,
      space.id,
      demo.email,
      "contributor",
    );
    await memory.accept(demo, invite.token);
  } else if (!membership.active || membership.role !== "contributor") {
    throw new FixtureStateError(
      "Demo access was changed. It was preserved; request --restore-demo-membership explicitly to issue and accept a fresh demo invitation.",
    );
  }
  const input = (key, text, kind = "fact") => ({
    text,
    kind,
    basis: "observed_outcome",
    evidence:
      "Synthetic fixture generated by the guarded sandbox operator at the user's request; not a real personal fact or an external agent action.",
    entities: [{ type: "project", name: "Sandbox Demo" }],
    idempotencyKey: `sandbox-own-account-v2-${key}`,
  });
  const ownPrivate = await memory.remember(
    owner,
    input(
      "owner-private",
      "Synthetic fixture: this personal test note stays private to the sandbox owner.",
    ),
  );
  const demoPrivate = await memory.remember(
    demo,
    input(
      "demo-private",
      "Synthetic fixture: the demo teammate's unshared planning note.",
    ),
  );
  const progress = await memory.remember(
    demo,
    input(
      "demo-progress",
      "Synthetic fixture: Demo Teammate completed the graph import for Sandbox Demo.",
      "task",
    ),
  );
  const decision = await memory.remember(
    demo,
    input(
      "demo-decision",
      "Synthetic fixture: Demo Teammate proposed reviewing the Sandbox Demo dashboard next.",
      "decision",
    ),
  );
  const shared = [progress.memory, decision.memory];
  // Stable share operation keys preserve a user's later retraction on an ordinary seed rerun.
  for (const record of shared)
    await memory.share(
      demo,
      record.id,
      space.id,
      true,
      "own-account-fixture-v2",
    );
  const visibleSharedIds = [],
    retractedIds = [];
  for (const record of shared) {
    try {
      assert.equal((await memory.get(owner, record.id)).id, record.id);
    } catch (error) {
      if (error?.status === 403 || error?.status === 404) {
        retractedIds.push(record.id);
        continue;
      }
      throw error;
    }
    visibleSharedIds.push(record.id);
  }
  const denied = (error) => error?.status === 403 || error?.status === 404;
  await assert.rejects(memory.get(owner, demoPrivate.memory.id), denied);
  const ownShares = await memory.query(
    "MATCH (m:Memory {id:$id})-[:SHARED_IN {active:true}]->(:Space)<-[:MEMBER_OF {active:true}]-(:Person {id:$user}) RETURN m.id AS id LIMIT 1",
    { id: ownPrivate.memory.id, user: demo.userId },
    true,
  );
  const ownPrivateShared = ownShares.length > 0;
  if (ownPrivateShared)
    assert.equal(
      (await memory.get(demo, ownPrivate.memory.id)).id,
      ownPrivate.memory.id,
    );
  else await assert.rejects(memory.get(demo, ownPrivate.memory.id), denied);
  let update;
  if (options.demoUpdate) {
    update = (
      await memory.remember(
        demo,
        input(
          `progress-${options.demoUpdate}`,
          `Synthetic fixture: Demo Teammate finished another sandbox verification step (${options.demoUpdate}).`,
          "task",
        ),
      )
    ).memory;
    await memory.share(
      demo,
      update.id,
      space.id,
      true,
      `demo-update-${options.demoUpdate}`,
    );
    assert.equal((await memory.get(owner, update.id)).id, update.id);
  }
  return {
    space: { id: space.id, name: space.name },
    ownPrivateId: ownPrivate.memory.id,
    ownPrivateShared,
    demoPrivateId: demoPrivate.memory.id,
    demoSharedIds: visibleSharedIds,
    demoRetractedIds: retractedIds,
    demoUpdateId: update?.id,
    privacyChecks: "passed",
  };
}

async function main() {
  const options = parseSeedArgs(process.argv.slice(2));
  assertSandbox(process.env);
  const clerk = createClerkClient({
    secretKey: process.env.CLERK_SECRET_KEY,
    publishableKey: process.env.CLERK_PUBLISHABLE_KEY,
  });
  const instance = await clerk.instance.get();
  if (
    instance.id !== process.env.SANDBOX_CLERK_INSTANCE_ID ||
    instance.environmentType !== "development"
  ) {
    throw new Error("Seed refused: Clerk returned a different instance.");
  }
  const ownerCandidates = await clerk.users.getUserList({
    emailAddress: [options.ownerEmail],
    limit: 10,
  });
  const ownerUser = ownerCandidates.data.find(
    (u) =>
      u.primaryEmailAddress?.emailAddress.toLowerCase() ===
        options.ownerEmail &&
      u.primaryEmailAddress.verification?.status === "verified",
  );
  if (!ownerUser)
    throw new FixtureStateError(
      "Sign into the sandbox once with your own email and verify it before seeding; the operator never creates or impersonates a real person's account.",
    );
  const ownerTag = createHash("sha256")
    .update(ownerUser.id)
    .digest("hex")
    .slice(0, 12);
  const demoEmail = `teammate-${ownerTag}+clerk_test@example.com`;
  if (!options.apply) {
    console.log(
      JSON.stringify({
        dryRun: true,
        ownerEmail: options.ownerEmail,
        demoEmail,
        demoUpdate: options.demoUpdate,
        restoreDemoMembership: options.restoreDemoMembership,
        graphs: ["sandbox_profiles", "sandbox_memory"],
      }),
    );
    return;
  }
  const { connectMemoryStore } = await import("../dist/memory.js");
  const { connectUserStore } = await import("../dist/users.js");
  const { fromClerkUser } = await import("../dist/clerk-users.js");
  const memory = await connectMemoryStore();
  let profiles;
  try {
    profiles = await connectUserStore();
    const existingDemo = await clerk.users.getUserList({
      emailAddress: [demoEmail],
      limit: 10,
    });
    const demoUser =
      existingDemo.data[0] ??
      (await clerk.users.createUser({
        emailAddress: [demoEmail],
        firstName: "Demo Teammate",
        lastName: "Sandbox",
        skipPasswordRequirement: true,
      }));
    for (const user of [ownerUser, demoUser]) {
      await profiles.upsert(fromClerkUser(user));
    }
    const actor = (user) => ({
      userId: user.id,
      name: user.fullName,
      email: user.primaryEmailAddress.emailAddress,
      clientId: "sandbox-fixtures",
    });
    const result = await seedWorkspace(
      memory,
      actor(ownerUser),
      actor(demoUser),
      options,
    );
    console.log(
      JSON.stringify({
        seeded: true,
        ownerEmail: options.ownerEmail,
        demoEmail,
        ...result,
      }),
    );
  } finally {
    await Promise.all([profiles?.close(), memory.close()]);
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main().catch((error) => {
    console.error(
      error instanceof FixtureStateError
        ? error.message
        : "Sandbox seed failed. No credentials printed. Check sandbox targeting, provider access, and fixture permissions.",
    );
    process.exitCode = 1;
  });
}
